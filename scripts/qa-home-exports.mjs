import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const base = 'http://127.0.0.1:8788';
const evidence = '.gstack/homepage-study-2026-10-03';
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
  await context.addInitScript(() => { window.print = () => { window.__printRequested = true; }; });
  const page = await context.newPage();
  await page.goto(`${base}/mocks/?home=3&view=end`);
  await page.getByRole('button',{name:'Share fable'}).click();
  await page.getByRole('button',{name:'Copy preview link'}).click();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(copied.includes('shared=sample')); assert.ok(!copied.includes('story='));
  const newPage = context.waitForEvent('page');
  await page.getByRole('link',{name:'Preview recipient view'}).click();
  const recipient = await newPage;
  await expect(recipient.locator('.prose')).toBeVisible();
  await expect(recipient.locator('.shared-note')).toContainText('local only');
  await recipient.close();
  await page.screenshot({path:`${evidence}/share-1440.png`});
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'Download fable'}).click();
  const popupEvent = context.waitForEvent('page');
  await page.getByRole('button',{name:/Save as PDF/}).click();
  const print = await popupEvent;
  await expect.poll(() => print.evaluate(() => window.__printRequested)).toBe(true);
  await expect(print.locator('h1')).toHaveText('The Hall of Affairs');
  assert.ok(await print.locator('img').evaluateAll(images => images.length === 2 && images.every(i=>i.complete && i.naturalWidth > 0)));
  const pdf = await print.pdf({path:`${evidence}/the-hall-of-affairs.pdf`,format:'A4',printBackground:true});
  assert.equal(pdf.subarray(0,4).toString(),'%PDF'); await print.close();
  await page.goto(`${base}/mocks/compare.html`);
  await expect(page.locator('.card')).toHaveCount(8);
  await page.evaluate(async () => { await Promise.all([...document.images].map(i=>i.decode())); });
  await page.screenshot({path:`${evidence}/comparison.png`,fullPage:true});
  await page.getByRole('link',{name:/03 One line/}).click();
  await expect(page.getByRole('heading',{name:'Learn through stories.'})).toBeVisible();
  await page.goto(`${base}/`);
  await page.getByRole('button',{name:'Read the sample'}).click();
  await expect(page.getByRole('button',{name:'Begin reading',exact:true})).toBeVisible();
  const result = 'PASS: clipboard link, recipient preview, PDF print request and rendered PDF, eight linked comparison cards, original reader smoke check.';
  await writeFile(`${evidence}/exports-check.txt`,result+'\n'); console.log(result);
  await context.close();
} finally { await browser.close(); }
